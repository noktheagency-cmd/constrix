function money(value) {
  return Number(value.toFixed(2))
}

function quote(row) {
  const glass = Math.max(row.glassWidth, row.glassHeight)
  let fit = "uygun"
  if (row.weight > row.capacityKg) fit = "tutum"
  else if (row.vehicle === "standart" && glass > row.maxGlassMm) fit = "olcu"
  const km = row.roundTrip ? row.km * 2 : row.km
  const cost = fit === "uygun" ? money(km * row.tariff + row.loadCost + row.waitCost + row.extra) : null
  const days = Math.ceil(km / row.speed)
  return { km, cost, days, fit }
}

export async function seedHaulHistory(prisma) {
  const orgs = await prisma.organization.findMany({ select: { id: true } })
  let written = 0
  for (const org of orgs) {
    for (const row of HAULS) {
      const math = quote(row)
      const data = {
        organizationId: org.id,
        fromPlace: row.from,
        toPlace: row.to,
        km: math.km,
        weightKg: row.weight,
        volumeM3: row.volume,
        glassWidthMm: row.glassWidth,
        glassHeightMm: row.glassHeight,
        vehicle: row.vehicle,
        capacityKg: row.capacityKg,
        maxGlassMm: row.maxGlassMm,
        roundTrip: row.roundTrip,
        loadCost: row.loadCost,
        waitCost: row.waitCost,
        extra: row.extra,
        tariffPerKm: row.tariff,
        speedKmDay: row.speed,
        days: math.days,
        fit: math.fit,
        cost: math.cost,
        createdAt: new Date(row.at),
      }
      await prisma.haulQuote.upsert({
        where: { id: `haul-${org.id}-${row.key}` },
        update: data,
        create: { id: `haul-${org.id}-${row.key}`, ...data },
      })
      written += 1
    }
  }
  return written
}
